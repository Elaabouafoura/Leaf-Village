<script>
$('#projet').on('change', function() {
    var projetId = $(this).val();
    if (!projetId) return;

    $('#resultat').hide();
    $('#loading').show();

    $.ajax({
        url: "{{ route('financements.analyse.run') }}",
        type: "POST",
        data: {
            idProjet: projetId,
            _token: "{{ csrf_token() }}"
        },
        success: function(data) {
            $('#loading').hide();
            
            // Update data
            $('#score').text(data.score + '%');
            $('#recommandation').text(data.recommendation);
            $('#commentaire').text(data.comment);
            
            // Score animation
            updateScoreCircle(data.score);
            
            $('#resultat').show().hide().fadeIn(800);
        },
        error: function() {
            $('#loading').hide();
            alert("⚠️ Error during AI analysis");
        }
    });
});

function updateScoreCircle(score) {
    const circle = document.getElementById('scoreCircle');
    const percent = (score / 100) * 360;
    circle.style.setProperty('--score-percent', percent + 'deg');
}
</script>
